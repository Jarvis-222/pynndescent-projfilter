def load_fvecs(path, n_limit=None):
    """Read first n_limit records of an .fvecs file as a (n, dim) float32 array."""
    with open(path, "rb") as f:
        dim = struct.unpack("i", f.read(4))[0]
        f.seek(0)
        record_bytes = (dim + 1) * 4
        n_total = os.path.getsize(path) // record_bytes
        n = n_total if n_limit is None else min(n_limit, n_total)
        raw = np.frombuffer(f.read(n * record_bytes), dtype=np.int32).reshape(n, dim + 1)
    # column 0 is the dim header, columns 1: are the vector
    return np.ascontiguousarray(raw[:, 1:].view(np.float32))


def load_gt_bin(path):
    """Read C++-format ground-truth file: (int32 n, int32 k, n*k int32 indices)."""
    with open(path, "rb") as f:
        n, k = struct.unpack("ii", f.read(8))
        gt = np.frombuffer(f.read(n * k * 4), dtype=np.int32).reshape(n, k).copy()
    return gt


def load_ivecs(path):
    """Read .ivecs file: per record (int32 dim, dim x int32 indices)."""
    with open(path, "rb") as f:
        dim = struct.unpack("i", f.read(4))[0]
        f.seek(0)
        record_bytes = (dim + 1) * 4
        n = os.path.getsize(path) // record_bytes
        raw = np.frombuffer(f.read(), dtype=np.int32).reshape(n, dim + 1)
    return raw[:, 1:].copy()


def compute_search_gt_brute(queries, base, k, batch=200):
    """Exact top-k Euclidean neighbors via batched matmul. ||a-b||^2 form."""
    qnorm = (queries.astype(np.float64) ** 2).sum(1)
    bnorm = (base.astype(np.float64) ** 2).sum(1)
    nq = queries.shape[0]
    gt = np.zeros((nq, k), dtype=np.int32)
    for s in range(0, nq, batch):
        e = min(s + batch, nq)
        dot = queries[s:e].astype(np.float64) @ base.T.astype(np.float64)
        d2 = qnorm[s:e, None] + bnorm[None, :] - 2.0 * dot
        part = np.argpartition(d2, k, axis=1)[:, :k]
        # sort within each row by actual distance
        order = np.argsort(np.take_along_axis(d2, part, 1), axis=1)
        gt[s:e] = np.take_along_axis(part, order, 1).astype(np.int32)
    return gt


def get_or_compute_search_gt(cache_path, queries, base, k):
    """Read cached search-GT or compute + cache fresh."""
    if cache_path.exists():
        gt = load_ivecs(cache_path)
        if gt.shape[0] == queries.shape[0] and gt.shape[1] >= k:
            return gt[:, :k]
    print(f"  computing exact search-GT (brute force)...", flush=True)
    t0 = time.perf_counter()
    gt = compute_search_gt_brute(queries, base, k)
    print(f"  computed in {time.perf_counter()-t0:.1f}s, caching to {cache_path}")
    # Write as .ivecs: per row [k, idx0, idx1, ...] as int32
    out = np.empty((gt.shape[0], gt.shape[1] + 1), dtype=np.int32)
    out[:, 0] = gt.shape[1]
    out[:, 1:] = gt
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    out.tofile(cache_path)
    return gt


def recall_at_k(pred, gt, k):
    """Average |pred[:,:k] intersect gt[:,:k]| / k across all vertices."""
    n = pred.shape[0]
    total = 0
    for i in range(n):
        total += len(set(pred[i, :k].tolist()) & set(gt[i, :k].tolist()))
    return total / (n * k)


def _print_phase(idx, total_time):
    """Print the per-phase breakdown of the descent loop."""
    lj = getattr(idx, "t_local_join", 0.0)
    apu = getattr(idx, "t_apply_update", 0.0)
    bc = getattr(idx, "t_build_candidates", 0.0)
    summed = lj + apu + bc
    other = max(total_time - summed, 0.0)
    def pct(x):
        return (100.0 * x / total_time) if total_time > 0 else 0.0
    print(
        f"  phase split:  local_join={lj:6.2f}s ({pct(lj):4.1f}%)  "
        f"apply_update={apu:6.2f}s ({pct(apu):4.1f}%)  "
        f"build_cand={bc:6.2f}s ({pct(bc):4.1f}%)  "
        f"other={other:6.2f}s ({pct(other):4.1f}%)"
    )


def build(data, n_neighbors, seed, use_filter, m, p_tau, verbose, tree_init):
    t0 = time.perf_counter()
    idx = pynndescent.NNDescent(
        data,
        n_neighbors=n_neighbors,
        random_state=seed,
        verbose=verbose,
        tree_init=tree_init,
        use_projection_filter=use_filter,
        num_projections=m,
        filter_confidence=p_tau,
    )
    elapsed = time.perf_counter() - t0
    return idx, elapsed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default="gist10k", choices=list(DATASETS.keys()))
    ap.add_argument("--n-neighbors", type=int, default=10)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--m", type=int, default=16, help="num projections")
    ap.add_argument("--p-tau", type=float, default=0.95, help="filter confidence")
    ap.add_argument("--no-tree-init", action="store_true",
                    help="Disable RP-tree init (random init only, matches C++ baseline)")
    ap.add_argument("--verbose", action="store_true")
    args = ap.parse_args()
    tree_init = not args.no_tree_init

    cfg = DATASETS[args.dataset]
    print(f"Dataset:    {args.dataset}")
    print(f"  base:     {cfg['base']}")
    print(f"  gt:       {cfg['gt']}")
    print(f"  n_subset: {cfg['n_subset']}")
    print(f"Config:     n_neighbors={args.n_neighbors} seed={args.seed} "
          f"m={args.m} p_tau={args.p_tau} tree_init={tree_init}")

    print("\nLoading data...", flush=True)
    t = time.perf_counter()
    data = load_fvecs(cfg["base"], n_limit=cfg["n_subset"])
    print(f"  shape={data.shape} dtype={data.dtype}  ({time.perf_counter()-t:.2f}s)")

    print("Loading ground truth...", flush=True)
    gt = load_gt_bin(cfg["gt"])
    print(f"  shape={gt.shape}")
    if gt.shape[0] != data.shape[0]:
        sys.exit(f"ERROR: gt n={gt.shape[0]} != data n={data.shape[0]}")
    if gt.shape[1] < args.n_neighbors:
        sys.exit(f"ERROR: gt k={gt.shape[1]} < n_neighbors={args.n_neighbors}")

    # Optional search benchmark data
    queries = None
    search_gt = None
    if cfg.get("queries") and cfg.get("search_gt"):
        print("Loading query set + search ground truth...", flush=True)
        queries = load_fvecs(cfg["queries"])
        search_gt = get_or_compute_search_gt(
            cfg["search_gt"], queries, data, args.n_neighbors
        )
        print(f"  queries={queries.shape}  search_gt={search_gt.shape}")

    # Warm up Numba JIT on tiny synthetic so timing reflects compute, not compile.
    print("\nWarming up Numba JIT...", flush=True)
    t = time.perf_counter()
    rng = np.random.default_rng(42)
    warm = rng.standard_normal((200, 16)).astype(np.float32)
    _ = pynndescent.NNDescent(warm, n_neighbors=5, random_state=0,
                              tree_init=tree_init,
                              use_projection_filter=False, verbose=False)
    _ = pynndescent.NNDescent(warm, n_neighbors=5, random_state=0,
                              tree_init=tree_init,
                              use_projection_filter=True, num_projections=args.m,
                              filter_confidence=args.p_tau, verbose=False)
    print(f"  done ({time.perf_counter()-t:.1f}s)")

    print("\n" + "=" * 60)
    print("VANILLA PyNNDescent")
    print("=" * 60)
    idx_v, time_v = build(data, args.n_neighbors, args.seed, False,
                           args.m, args.p_tau, args.verbose, tree_init)
    recall_v = recall_at_k(idx_v.neighbor_graph[0], gt, args.n_neighbors)
    print(f"  build time:   {time_v:.2f} s")
    print(f"  recall@{args.n_neighbors}:    {recall_v:.4f}")
    print(f"  dist_comps:   {idx_v.n_dist_comps:,}")
    print(f"  filter_skips: {idx_v.n_filter_skips:,} (should be 0)")
    _print_phase(idx_v, time_v)
    search_recall_v = None
    qps_v = None
    if queries is not None:
        tq = time.perf_counter()
        pred_q, _ = idx_v.query(queries, k=args.n_neighbors)
        query_time_v = time.perf_counter() - tq
        search_recall_v = recall_at_k(pred_q, search_gt, args.n_neighbors)
        qps_v = queries.shape[0] / query_time_v
        print(f"  query time:   {query_time_v:.3f} s ({qps_v:.0f} qps)")
        print(f"  search recall@{args.n_neighbors}: {search_recall_v:.4f}")

    print("\n" + "=" * 60)
    print(f"PyNNDescent + ProjFilter (m={args.m}, p_tau={args.p_tau})")
    print("=" * 60)
    idx_f, time_f = build(data, args.n_neighbors, args.seed, True,
                           args.m, args.p_tau, args.verbose, tree_init)
    recall_f = recall_at_k(idx_f.neighbor_graph[0], gt, args.n_neighbors)
    print(f"  build time:   {time_f:.2f} s")
    print(f"  recall@{args.n_neighbors}:    {recall_f:.4f}")
    print(f"  dist_comps:   {idx_f.n_dist_comps:,}")
    print(f"  filter_skips: {idx_f.n_filter_skips:,}")
    _print_phase(idx_f, time_f)
    search_recall_f = None
    qps_f = None
    if queries is not None:
        tq = time.perf_counter()
        pred_q, _ = idx_f.query(queries, k=args.n_neighbors)
        query_time_f = time.perf_counter() - tq
        search_recall_f = recall_at_k(pred_q, search_gt, args.n_neighbors)
        qps_f = queries.shape[0] / query_time_f
        print(f"  query time:   {query_time_f:.3f} s ({qps_f:.0f} qps)")
        print(f"  search recall@{args.n_neighbors}: {search_recall_f:.4f}")

    print("\n" + "=" * 60)
    print("SUMMARY")
    print("=" * 60)
    print(f"  Time ratio (filter/vanilla):    {time_f/time_v:.3f}x")
    if idx_v.t_local_join > 0:
        lj_ratio = idx_f.t_local_join / idx_v.t_local_join
        lj_save_pct = 100.0 * (1.0 - lj_ratio)
        print(
            f"  Local-join time (vanilla):      {idx_v.t_local_join:.2f}s "
            f"({100.0*idx_v.t_local_join/time_v:.1f}% of build)"
        )
        print(
            f"  Local-join time (filter):       {idx_f.t_local_join:.2f}s "
            f"({100.0*idx_f.t_local_join/time_f:.1f}% of build)"
        )
        print(
            f"  Local-join savings:             {lj_save_pct:+.1f}%  "
            f"(ceiling for filter wall-clock impact)"
        )
    print(f"  Construction recall delta:      {recall_f - recall_v:+.4f}")
    dc_saved = idx_v.n_dist_comps - idx_f.n_dist_comps
    dc_saved_pct = 100.0 * dc_saved / max(idx_v.n_dist_comps, 1)
    print(f"  Dist comps saved:               {dc_saved:,} ({dc_saved_pct:+.1f}%)")
    print(f"  Filter fire rate:               {100.0*idx_f.n_filter_skips/max(idx_v.n_dist_comps, 1):.1f}%")
    if search_recall_v is not None:
        print(f"  Search recall delta:            "
              f"{search_recall_f - search_recall_v:+.4f}  "
              f"(vanilla={search_recall_v:.4f} filter={search_recall_f:.4f})")
        print(f"  QPS ratio (filter/vanilla):     {qps_f/qps_v:.3f}x")
    gate1 = (recall_v - recall_f) <= 0.01
    gate2 = idx_f.n_dist_comps < idx_v.n_dist_comps
    print(f"  Gate 1 (construction recall <= 1pp loss): {'PASS' if gate1 else 'FAIL'}")
    print(f"  Gate 2 (filter actually fires):           {'PASS' if gate2 else 'FAIL'}")
    if search_recall_v is not None:
        gate4 = (search_recall_v - search_recall_f) <= 0.01
        print(f"  Gate 4 (search recall <= 1pp loss):       {'PASS' if gate4 else 'FAIL'}")


if __name__ == "__main__":
    main()
